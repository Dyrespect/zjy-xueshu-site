/** <img> 要的 src / srcSet（最大那档当 src） */
export function mediaSrc(m: SiteMedia): { src: string; srcSet: string } {
  const srcSet = m.widths.map((w) => `${MEDIA_BASE}/${m.id}-${w}.webp ${w}w`).join(", ");
  return { src: `${MEDIA_BASE}/${m.id}-${m.widths[m.widths.length - 1]}.webp`, srcSet };
}

